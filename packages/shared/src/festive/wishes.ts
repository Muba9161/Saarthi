const FALLBACK_LOCALE = 'en-IN';

/** The festival's wish in `locale` (any spelling the language catalogue resolves), English otherwise. */
export function festiveWish(key: FestivalKey, locale: string | null | undefined): string {
  const resolved = resolveLocale(locale ?? null);
  return FESTIVE_WISHES[resolved]?.[key] ?? FESTIVE_WISHES[FALLBACK_LOCALE]![key];
}

/** "from everyone at VorldX Saarthi", in `locale`. */
export function festiveSignature(locale: string | null | undefined): string {
  const resolved = resolveLocale(locale ?? null);
  return FESTIVE_SIGNATURE[resolved] ?? FESTIVE_SIGNATURE[FALLBACK_LOCALE]!;
}

/**
 * The wish addressed to someone: "Happy Gurpurab, Aarav!". Without a usable
 * first name it is the wish alone. Urdu takes the Arabic comma.
 */
export function festiveGreeting(
  key: FestivalKey,
  locale: string | null | undefined,
  firstName?: string | null,
): string {
  const wish = festiveWish(key, locale);
  const name = (firstName ?? '').trim().split(/\s+/)[0]?.slice(0, 24) ?? '';
  if (!name || name.includes('@')) return wish;
  const comma = resolveLocale(locale ?? null) === 'ur-IN' ? '، ' : ', ';
  return `${wish}${comma}${name}!`;
}
